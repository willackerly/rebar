#!/usr/bin/env bash
# gen-released-blobs.sh — list every released version of rebar's scripts.
#
# `rebar migrate` deletes a legacy copy it cannot run safely (steward,
# inbox-watch, ...) only when the copy is byte-identical to a version rebar
# has released. Installs made by the installer are release trees without git
# history, so the CLI carries this list (go:embed) instead of reading
# history: cli/internal/migrate/released-blobs.txt, one `<git blob id> <file
# name>` per line, for scripts/*.sh, templates/project-bootstrap/scripts/*.sh
# and the template's scripts/README.md at every release tag and release
# branch.
#
# It also stores the content of every released version of the source
# scanners (check-todos, check-contract-refs, check-contract-headers,
# check-freshness) in cli/internal/migrate/released/<blob id>, so migrate can
# tell a copy that differs from a release only in settings (directories,
# extensions) from a real customization, without git history.
#
# Run at release time, after tagging:  scripts/gen-released-blobs.sh
# Check it is current:                 scripts/gen-released-blobs.sh --check
# (cli/internal/migrate's tests fail when a local tag is missing from it.)

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/cli/internal/migrate/released-blobs.txt"

refs=()
while IFS= read -r r; do refs+=("$r"); done < <(
  git -C "$ROOT" for-each-ref --format='%(refname)' 'refs/tags/v*' 'refs/heads/release/*' 'refs/remotes/origin/release/*'
)
[ ${#refs[@]} -gt 0 ] || { echo "gen-released-blobs: no release tags or branches in $ROOT" >&2; exit 1; }

generate() {
  echo "# Released rebar script blobs: <git blob id> <file name>. Generated by"
  echo "# scripts/gen-released-blobs.sh from release tags and branches; do not edit."
  # -m: also list blobs that only exist in a merge commit (a conflict
  # resolution), which `git log --raw` skips by default.
  git -C "$ROOT" log -m --format= --raw --no-abbrev --no-renames "${refs[@]}" \
      -- scripts templates/project-bootstrap/scripts \
    | awk '$1 ~ /^:/ {
        path = $6
        n = split(path, parts, "/")
        name = parts[n]
        dir = substr(path, 1, length(path) - length(name) - 1)
        if (dir != "scripts" && dir != "templates/project-bootstrap/scripts") next
        if (name !~ /\.sh$/ && name != "README.md") next
        if ($4 !~ /^0+$/) print $4, name
        if ($3 !~ /^0+$/) print $3, name
      }' \
    | LC_ALL=C sort -u
}

SCANNERS="check-todos.sh check-contract-refs.sh check-contract-headers.sh check-freshness.sh"
DIR="$ROOT/cli/internal/migrate/released"

scanner_blobs() {
  local n
  for n in $SCANNERS; do
    awk -v n="$n" '$2 == n { print $1 }' "$1"
  done
}

if [ "${1:-}" = "--check" ]; then
  missing=0
  for h in $(scanner_blobs "$OUT"); do
    [ -f "$DIR/$h" ] || missing=1
  done
  if [ $missing -eq 0 ] && diff -q <(generate) "$OUT" >/dev/null 2>&1; then
    echo "OK: released-blobs.txt is current"
    exit 0
  fi
  echo "STALE: run scripts/gen-released-blobs.sh"
  exit 1
fi
generate > "$OUT"
rm -rf "$DIR"
mkdir -p "$DIR"
for h in $(scanner_blobs "$OUT"); do
  git -C "$ROOT" cat-file blob "$h" > "$DIR/$h"
done
echo "wrote $(grep -vc '^#' "$OUT") blobs to ${OUT#"$ROOT"/} and $(ls "$DIR" | wc -l | tr -d ' ') scanner sources to ${DIR#"$ROOT"/}"
