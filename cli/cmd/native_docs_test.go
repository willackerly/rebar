func withFiles(base map[string]string, extra map[string]string) map[string]string {
	out := map[string]string{}
	for k, v := range base {
		out[k] = v
	}
	for k, v := range extra {
		if v == "" {
			delete(out, k)
		} else {
			out[k] = v
		}
	}
	return out
}

