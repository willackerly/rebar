// check-version-bump (a post-commit hook that never blocks): when HEAD
// renames <contracts_dir>/CONTRACT-<id>.<old>.md to CONTRACT-<id>.<new>.md,
// append a pending notification to the federation outbox
// (<contracts_dir>/.state/pending-notifications.md, env REBAR_OUTBOX).
// Native port of scripts/check-version-bump.sh.
func init() {
	register(&Check{Name: "check-version-bump", Run: runVersionBump})
}

// outboxHeader starts a new outbox.
const outboxHeader = "# Pending Consumer Notifications\n" +
	"\n" +
	"<!-- format: rebar-pending-notifications-v1 -->\n" +
	"\n" +
	"Auto-generated by `scripts/check-version-bump.sh` (post-commit hook).\n" +
	"Owner runs `scripts/flush-notifications.sh` to deliver pending entries\n" +
	"via the `ask_<consumer>_featurerequest` gate.\n" +
	"\n" +
	"Each entry: contract id, old → new version, detected timestamp,\n" +
	"commit, status (pending | sent | dropped). `flush-notifications.sh`\n" +
	"auto-classifies severity (breaking | additive | patch) from the\n" +
	"semver delta unless --severity overrides.\n" +
	"\n"

var pendingEntry = regexp.MustCompile(`^- \*\*status:\*\* pending`)

func runVersionBump(ctx *Context, args []string) int {
	contractsDir := contracts.Dir(ctx.Root)
	top, code := gitx.Run(ctx.WorkDir(), nil, "rev-parse", "--show-toplevel")
	if code != 0 {
		return 0
	}
	repo := strings.TrimRight(top, "\n")
	outbox := config.Getenv("REBAR_OUTBOX")
	if outbox == "" {
		outbox = contractsDir + "/.state/pending-notifications.md"
	}
	if !filepath.IsAbs(outbox) {
		outbox = filepath.Join(repo, outbox)
	}

	out, code := gitx.Run(repo, nil, "diff-tree", "--no-commit-id", "--name-status", "-r", "--diff-filter=R", "--find-renames=80%", "HEAD")
	if code != 0 {
		return code // set -e and pipefail end the script with git's status
	}
	// The script's awk: renames whose old and new paths (split on blanks, as
	// awk fields) both start with <contracts_dir>/CONTRACT- and end in .md.
	prefix := contractsDir + "/CONTRACT-"
	var renames [][2]string
	for _, line := range textLines([]byte(out)) {
		f := strings.FieldsFunc(line, func(r rune) bool { return r == ' ' || r == '\t' })
		if len(f) < 3 || !strings.HasPrefix(f[0], "R") ||
			!strings.HasPrefix(f[1], prefix) || !strings.HasPrefix(f[2], prefix) ||
			!strings.HasSuffix(f[1], ".md") || !strings.HasSuffix(f[2], ".md") {
			continue
		}
		renames = append(renames, [2]string{f[1], f[2]})
	}
	if len(renames) == 0 {
		return 0
	}

	if err := os.MkdirAll(filepath.Dir(outbox), 0o755); err != nil {
		fmt.Fprintf(ctx.Stderr, "mkdir: %s: %v\n", filepath.Dir(outbox), err)
		return 1
	}
	if _, err := os.Stat(outbox); err != nil {
		if err := os.WriteFile(outbox, []byte(outboxHeader), 0o644); err != nil {
			fmt.Fprintf(ctx.Stderr, "check-version-bump: %v\n", err)
			return 1
		}
	}
	now := time.Now().UTC().Format("2006-01-02T15:04:05Z")
	shortSHA := gitx.Subst(repo, "rev-parse", "--short", "HEAD")

	var entries strings.Builder
	for _, r := range renames {
		oldID, oldVer := contractPathVersion(r[0])
		newID, newVer := contractPathVersion(r[1])
		if oldID != newID || newID == "" {
			continue // renamed to another contract, not a version bump
		}
		fmt.Fprintf(&entries, "\n## %s: %s → %s\n- **detected:** %s\n- **status:** pending\n- **commit:** %s\n- **old_path:** %s\n- **new_path:** %s\n- **severity:** (auto)\n",
			newID, oldVer, newVer, now, shortSHA, r[0], r[1])
	}
	if entries.Len() > 0 {
		f, err := os.OpenFile(outbox, os.O_APPEND|os.O_WRONLY, 0o644)
		if err != nil {
			fmt.Fprintf(ctx.Stderr, "check-version-bump: %v\n", err)
			return 1
		}
		_, werr := f.WriteString(entries.String())
		if cerr := f.Close(); werr == nil {
			werr = cerr
		}
		if werr != nil {
			fmt.Fprintf(ctx.Stderr, "check-version-bump: %v\n", werr)
			return 1
		}
	}

	// pending=$(grep -cE … | tr -d ' \n' || echo 0): with no pending line
	// grep -c prints 0 and fails, so the script reads "00".
	pending := "0"
	data, err := os.ReadFile(outbox)
	if err == nil {
		n := 0
		for _, line := range textLines(data) {
			if pendingEntry.MatchString(line) {
				n++
			}
		}
		pending = fmt.Sprint(n)
		if n == 0 {
			pending = "00"
		}
	}
	if pending != "0" {
		fmt.Fprintf(ctx.Stderr, "rebar: contract version bump recorded → outbox has %s pending notification(s); flush with scripts/flush-notifications.sh\n", pending)
	}
	return 0
}

// contractPathVersion is parse_contract_path: the id and version of
// <dir>/CONTRACT-<id>.<MAJOR>.<MINOR>[.<PATCH>].md, both "" when the name
// does not end in a version. The id joins the fields before the version
// with dots, as the script's awk does (skipping the dot after an empty
// leading field).
func contractPathVersion(p string) (id, version string) {
	base := p
	if i := strings.LastIndexByte(base, '/'); i >= 0 {
		base = base[i+1:]
	}
	if base != ".md" {
		base = strings.TrimSuffix(base, ".md")
	}
	base = strings.TrimPrefix(base, "CONTRACT-")
	f := strings.Split(base, ".")
	n := len(f)
	if base == "" || n < 2 || !allDigits(f[n-1]) || !allDigits(f[n-2]) {
		return "", ""
	}
	end := n - 2
	version = f[n-2] + "." + f[n-1]
	if n >= 3 && allDigits(f[n-3]) {
		end = n - 3
		version = f[n-3] + "." + version
	}
	for _, field := range f[:end] {
		if id != "" {
			id += "."
		}
		id += field
	}
	return id, version
}

// allDigits is awk's /^[0-9]+$/.
func allDigits(s string) bool {
	if s == "" {
		return false
	}
	for i := 0; i < len(s); i++ {
		if s[i] < '0' || s[i] > '9' {
			return false
		}
	}
	return true
}
